import { rgb565 } from "./build-station-art.mjs";

// Fixed, public project art only. These are the same sources used on the site;
// never accept a URL, filename or image from a payment/serial command.
export const SCENE_ART = [
  { key: "School", cause: "school-supplies", file: "station-photos/school.jpg", url: "https://giveth.mypinata.cloud/ipfs/QmfZ6YaqHL6FnS3WSXrhAZv1ukahK4JUacZvX7phofqiFg" },
  { key: "Vida", cause: "vida-verde", file: "station-photos/vida.jpg", url: "https://giveth.mypinata.cloud/ipfs/QmcStBE4boayqj8rweKLikbBVyesDxfkDharb3V8rT7mQP" },
  { key: "Solar", cause: "solar-foundation", file: "solar-foundation-community.jpg" },
  { key: "Animals", cause: "animal-ethics", file: "animal-ethics-mark.png", contain: true },
  { key: "Burundi", cause: "burundi", file: "station-photos/burundi.jpg", url: "https://giveth.mypinata.cloud/ipfs/QmbgeaiXhof9iLzg8F8nQ5pP9QwYfsQKdHGq2ecGpqKrck" },
];
export const SCENE_PHOTO_WIDTH = 192, SCENE_PHOTO_HEIGHT = 144;

export async function buildStationScenes(sharpDirectory, check = false) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const require = createRequire(sharpDirectory ? resolve(sharpDirectory, "package.json") : import.meta.url);
  const sharp = require("sharp");
  const width = SCENE_PHOTO_WIDTH, height = SCENE_PHOTO_HEIGHT;
  const blocks = [];
  await mkdir(resolve(root, "public/station-photos"), { recursive: true });
  await mkdir(resolve(root, "work/station-art"), { recursive: true });
  for (const asset of SCENE_ART) {
    const target = resolve(root, "public", asset.file);
    let input;
    try { input = await readFile(target); }
    catch (error) {
      if (check || !asset.url || error.code !== "ENOENT") throw error;
      const response = await fetch(asset.url, { signal: AbortSignal.timeout(30000), redirect: "error" });
      if (!response.ok || Number(response.headers.get("content-length")) > 10_000_000) throw new Error("Project image unavailable.");
      input = Buffer.from(await response.arrayBuffer());
      if (input.length > 10_000_000) throw new Error("Project image is too large.");
      // Decode before persisting. Only this offline builder touches the network.
      await sharp(input, { limitInputPixels: 40_000_000 }).metadata();
      await writeFile(target, input);
    }
    const pixels = await sharp(input, { limitInputPixels: 40_000_000 })
      .resize(width, height, { fit: "contain", position: "centre", background: "#201131" })
      .flatten({ background: "#0f0519" }).removeAlpha().raw().toBuffer();
    const rows = [];
    for (let at = 0; at < pixels.length; at += 48) {
      const words = [];
      for (let p = at; p < Math.min(at + 48, pixels.length); p += 3) words.push(`0x${rgb565(pixels[p], pixels[p + 1], pixels[p + 2]).toString(16).padStart(4, "0")}`);
      rows.push(`  ${words.join(", ")},`);
    }
    blocks.push(`// ${asset.cause}; source ${asset.file}; SHA256 ${createHash("sha256").update(input).digest("hex")}\nconst uint16_t ${asset.key}[Width * Height] PROGMEM = {\n${rows.join("\n")}\n};`);
    if (!check) await sharp(pixels, { raw: { width, height, channels: 3 } }).png().toFile(resolve(root, "work/station-art", `${asset.key}.png`));
  }
  const bytes = width * height * SCENE_ART.length * 2;
  const header = `#pragma once\n#include <Arduino.h>\n#include <pgmspace.h>\n// Generated by scripts/build-station-scenes.mjs. Flash-only RGB565 art.\n// Five ${width}x${height} photos; ${bytes} flash bytes, zero heap/image decoder/network.\nnamespace StationScenes {\nconstexpr uint16_t Width = ${width}, Height = ${height};\n${blocks.join("\n\n")}\n}\n`;
  const target = resolve(root, "firmware/chogcare_station/StationScenes.h");
  if (check) { if (await readFile(target, "utf8") !== header) throw new Error("Station scene art is stale."); }
  else await writeFile(target, header);
  console.log(`${check ? "Verified" : "Built"} five station initiative images (${bytes} flash bytes).`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await buildStationScenes(process.argv.slice(2).find(arg => arg !== "--check"), process.argv.includes("--check"));
}
