import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createRequire } from "node:module";
import { resolve, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { rgb565, STATION_ART_BACKGROUND } from "./build-station-art.mjs";

export const STATION_BRAND_SOURCE = "firmware/assets/chogcare-kindness.png";
export const STATION_BRAND_SIZES = Object.freeze([["WaitingArt", 176, 18], ["ThanksArt", 128, 14]]);

// Rounded corners are composited against the exact TFT background. The board
// reads RGB565 directly from flash without allocating or decoding an image.
export async function buildStationBrand(sharpDirectory, check = false) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const require = createRequire(sharpDirectory ? resolve(sharpDirectory, "package.json") : import.meta.url);
  const sharp = require("sharp");
  const source = await readFile(resolve(root, STATION_BRAND_SOURCE));
  const sha = createHash("sha256").update(source).digest("hex");
  const declarations = [], previews = [];
  for (const [name, size, radius] of STATION_BRAND_SIZES) {
    const mask = Buffer.from(`<svg width="${size}" height="${size}"><rect width="${size}" height="${size}" rx="${radius}" fill="white"/></svg>`);
    const resized = await sharp(source).resize(size, size, { fit: "contain", background: "#0f0519" }).ensureAlpha().png().toBuffer();
    const rounded = await sharp(resized).composite([{ input: mask, blend: "dest-in" }]).png().toBuffer();
    const pixels = await sharp(rounded).flatten({ background: "#0f0519" }).removeAlpha().raw().toBuffer();
    const words = [], preview = Buffer.alloc(size * size * 3);
    for (let at = 0; at < pixels.length; at += 3) {
      const word = rgb565(pixels[at], pixels[at + 1], pixels[at + 2]);
      words.push(`0x${word.toString(16).padStart(4, "0")}`);
      preview[at] = Math.round((word >> 11 & 31) * 255 / 31);
      preview[at + 1] = Math.round((word >> 5 & 63) * 255 / 63);
      preview[at + 2] = Math.round((word & 31) * 255 / 31);
    }
    if (words.length !== size * size || rgb565(...STATION_ART_BACKGROUND) !== 0x0823) throw new Error("Invalid station brand bitmap");
    const rows = [];
    for (let at = 0; at < words.length; at += 16) rows.push(`  ${words.slice(at, at + 16).join(", ")},`);
    declarations.push(`constexpr uint16_t ${name}Size = ${size};\nconst uint16_t ${name}[${size} * ${size}] PROGMEM = {\n${rows.join("\n")}\n};`);
    previews.push({ name, size, preview });
  }
  const output = `#pragma once\n#include <Arduino.h>\n#include <pgmspace.h>\n// Generated by scripts/build-station-brand.mjs from ${STATION_BRAND_SOURCE}.\n// Source SHA256: ${sha}\n// Rounded RGB565 artwork; 94,720 flash bytes, no runtime image buffer.\nnamespace StationBrand {\n${declarations.join("\n\n")}\n}\n`;
  const target = resolve(root, "firmware/chogcare_station/StationBrand.h");
  if (check) {
    if (await readFile(target, "utf8") !== output) throw new Error("StationBrand.h is stale");
  } else {
    await writeFile(target, output);
    await mkdir(resolve(root, "work/station-art"), { recursive: true });
    for (const { name, size, preview } of previews) await sharp(preview, { raw: { width: size, height: size, channels: 3 } }).png().toFile(resolve(root, `work/station-art/${name}.png`));
  }
  console.log(`${check ? "Verified" : "Built"} rounded station artwork: waiting 176px / thanks 128px.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2), paths = args.filter(value => value !== "--check");
  if (paths.length > 1) throw new Error("Usage: node scripts/build-station-brand.mjs [sharp-package-directory] [--check]");
  await buildStationBrand(paths[0], args.includes("--check"));
}
